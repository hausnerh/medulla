#!/usr/bin/env python3
"""
Write a copy of a selection config with only the named samples enabled.

Cuts, categories, trees and sample paths stay as they are; every [[sample]]
gets `disable = false` if it is named and `disable = true` otherwise, and the
output name changes. Use it to run one sample of a big config interactively
(e.g. the dirt MC) and hand the result to batch/gore_cut_opt.py.

Usage
  sample_subset_toml.py selection/toml/gOre_1g1p_signal_osc_run2.toml --keep dirt \\
      --output gOre_1g1p_signal_osc_run2_dirt --out build/gOre_1g1p_signal_osc_run2_dirt.toml
"""
import argparse
import os
import re
import sys

NAME = re.compile(r'^\s*name\s*=\s*"([^"]+)"')
DISABLE = re.compile(r'^(\s*)disable\s*=\s*\w+')


def subset(text, keep, output):
    out, block = [], None

    def flush():
        if block is None:
            return
        name = next((m.group(1) for m in map(NAME.match, block) if m), None)
        on = name in keep
        val = 'false' if on else 'true'
        lines, done = [], False
        for ln in block:
            m = DISABLE.match(ln)
            if m:
                ln, done = f'{m.group(1)}disable = {val}\n', True
            lines.append(ln)
        if not done:                              # no disable key: insert after the header
            lines.insert(1, f'disable = {val}\n')
        out.extend(lines)
        found.append(name)

    found = []
    for ln in text.splitlines(keepends=True):
        s = ln.lstrip()
        if s.startswith('['):
            flush()
            block = [ln] if s.startswith('[[sample]]') else None
            if block is None:
                out.append(ln)
            continue
        (block if block is not None else out).append(ln)
    flush()
    missing = sorted(set(keep) - set(found))
    if missing:
        raise SystemExit(f'no [[sample]] named {missing} (have {found})')
    res, n = re.subn(r'(?m)^output\s*=\s*"[^"]*"', f'output = "{output}"', ''.join(out), count=1)
    if n != 1:
        raise SystemExit('no general.output in the config')
    return res


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('toml')
    ap.add_argument('--keep', nargs='+', required=True, help='sample names to enable')
    ap.add_argument('--output', required=True, help='medulla output name (.root is appended)')
    ap.add_argument('--out', required=True, help='config to write')
    a = ap.parse_args(argv)
    res = subset(open(a.toml).read(), set(a.keep), a.output)
    head = f'# GENERATED by batch/sample_subset_toml.py from {os.path.basename(a.toml)} (only {sorted(a.keep)} enabled).\n\n'
    with open(a.out, 'w') as f:
        f.write(head + res)
    print(f'wrote {a.out}: samples {sorted(a.keep)} enabled, output {a.output}.root')
    return 0


if __name__ == '__main__':
    sys.exit(main())
