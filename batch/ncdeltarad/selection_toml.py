#!/usr/bin/env python3
"""
Write the medulla selection config for the ncdeltarad sample.

It is the gOre signal config (cuts, categories and trees unchanged) with every
[[sample]] block replaced by one MC sample that reads the merged flat ML CAFs.
Generating it keeps the two in sync: rerun it whenever the signal config
changes, so the ncdeltarad and CV outputs always come from the same selection.

The sample gets its own output file. It must never sit next to `cv` in one
spineplot run (spineplot scales every MC sample to the data POT, which would
count NC resonant events twice); sample_check.py combines the two instead.

Usage
  selection_toml.py <persistent_base> --out build/gOre_1g1p_signal_ncdeltarad_run2.toml
  selection_toml.py <persistent_base> --out test.toml --path <one flat caf>   # quick test
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SIGNAL_TOML = os.path.join(HERE, '..', '..', 'selection', 'toml', 'gOre_1g1p_signal_osc_run2.toml')
SAMPLE = 'ncdeltarad'


def default_path(base):
    return os.path.join(base, 'spine', 'flatcaf', '*.flat.caf.root')


def make_toml(text, path, output, source):
    """The signal config `text` with its samples replaced by one ncdeltarad sample."""
    block = (f'[[sample]] # dedicated NC Δ radiative sample (batch/ncdeltarad), weights from the gen sidecar\n'
             f'name = "{SAMPLE}"\n'
             f'path = "{path}"\n'
             f'ismc = true\n'
             f'disable = false\n\n')
    out, skipping, inserted = [], False, False
    for ln in text.splitlines(keepends=True):
        s = ln.lstrip()
        if s.startswith('[[sample]]'):
            skipping = True
            if not inserted:
                out.append(block)
                inserted = True
            continue
        if skipping:
            if not s.startswith('['):
                continue                         # the sample's keys and the comments after it
            skipping = False
        out.append(ln)
    if not inserted:
        raise SystemExit('no [[sample]] block in the signal config')
    res, n = re.subn(r'(?m)^output\s*=\s*"[^"]*"', f'output = "{output}"', ''.join(out), count=1)
    if n != 1:
        raise SystemExit('no general.output in the signal config')
    head = (f'# GENERATED by batch/ncdeltarad/selection_toml.py from {source}.\n'
            f'# Do not edit: change the signal config and regenerate.\n\n')
    return head + res


def check(res, path, output):
    try:
        import tomllib
    except ImportError:                          # python < 3.11: skip the parse check
        return
    cfg = tomllib.loads(res)
    samples = cfg.get('sample', [])
    if [s.get('name') for s in samples] != [SAMPLE] or samples[0].get('path') != path:
        raise SystemExit(f'generated config has samples {[s.get("name") for s in samples]}, expected [{SAMPLE}]')
    if cfg['general']['output'] != output:
        raise SystemExit('generated config has the wrong output name')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('base', help='persistent_base of the campaign (holds spine/flatcaf)')
    ap.add_argument('--out', required=True, help='config to write')
    ap.add_argument('--path', help='flat CAF glob or file (default: <base>/spine/flatcaf/*.flat.caf.root)')
    ap.add_argument('--output', default='gOre_1g1p_signal_ncdeltarad_run2',
                    help='medulla output name (.root is appended)')
    ap.add_argument('--signal-toml', default=SIGNAL_TOML)
    a = ap.parse_args(argv)
    path = a.path or default_path(a.base)
    res = make_toml(open(a.signal_toml).read(), path, a.output, os.path.basename(a.signal_toml))
    check(res, path, a.output)
    with open(a.out, 'w') as f:
        f.write(res)
    print(f'wrote {a.out}: sample {SAMPLE} <- {path}, output {a.output}.root')
    return 0


if __name__ == '__main__':
    sys.exit(main())
